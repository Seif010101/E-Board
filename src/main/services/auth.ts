// Local accounts: sign-up, password login with rate limiting, TOTP 2FA, lock/unlock and the
// single in-memory session of this app instance. Pure Node (no Electron).

import { randomBytes, randomUUID } from 'node:crypto'
import QRCode from 'qrcode'
import type { LoginResult, TotpSetup } from '@shared/api'
import { DEFAULT_SETTINGS, type Language, type PublicUser, type StorageMode, type UserSettings } from '@shared/types'
import { AppError, fail, isUniqueViolation } from '../errors'
import type { Database } from '../db'
import { dummyHash, hashPassword, needsRehash, verifyPassword } from '../password'
import { LOGIN_POLICY, RateLimiter } from '../rateLimit'
import { createSecretBox, type SecretCipher } from '../secrets'
import { base32Decode, base32Encode, generateTotpSecret, otpauthUrl, verifyTotp } from '../totp'
import { createUsersRepo, toPublicUser, type UserRow } from '../repos/users'

export const CHALLENGE_TTL_MS = 5 * 60_000
export const CHALLENGE_MAX_ATTEMPTS = 5
const MAX_PENDING_CHALLENGES = 32
const GLOBAL_KEY = '*'

export interface AuthDeps {
  db: Database
  /** Electron safeStorage in production; null stores TOTP seeds as tagged plain text. */
  cipher: SecretCipher | null
  now?: () => number
}

interface Session {
  userId: string
  locked: boolean
  /** TOTP secret generated by totpBegin, not active until totpEnable verifies a code. */
  pendingTotp: Buffer | null
}

interface Challenge {
  userId: string
  expiresAt: number
  attempts: number
}

export interface SessionState {
  userId: string | null
  locked: boolean
}

export function createAuthService({ db, cipher, now = Date.now }: AuthDeps) {
  const users = createUsersRepo(db)
  const box = createSecretBox(cipher)
  const limiter = new RateLimiter(LOGIN_POLICY, now)
  const challenges = new Map<string, Challenge>()
  const decoyHash = dummyHash()
  let session: Session | null = null

  const userKey = (username: string) => `u:${username.toLowerCase()}`
  // Wrong codes are counted per account across challenges: a fresh login must not reset the budget.
  const totpKey = (userId: string) => `t:${userId}`

  const guardRate = (keys: string[]) => {
    const wait = Math.max(...keys.map((k) => limiter.retryAfter(k)))
    if (wait > 0) throw new AppError('rate_limited', undefined, wait)
  }

  const recordFailure = (keys: string[]): never => {
    const blocked = Math.max(...keys.map((k) => limiter.fail(k)))
    if (blocked > 0) throw new AppError('rate_limited', undefined, blocked)
    throw new AppError('invalid_credentials')
  }

  const startSession = (row: UserRow): PublicUser => {
    session = { userId: row.id, locked: false, pendingTotp: null }
    return toPublicUser(row)
  }

  /** The signed-in user's row; a vanished row ends the session. */
  const currentRow = (): UserRow => {
    if (!session) return fail('not_authenticated')
    const row = users.findById(session.userId)
    if (!row) {
      session = null
      return fail('not_authenticated')
    }
    return row
  }

  /** Verifies the signed-in user's password (rate limited like login). */
  const confirmPassword = async (row: UserRow, password: string): Promise<void> => {
    const keys = [userKey(row.username)]
    guardRate(keys)
    if (!(await verifyPassword(password, row.password_hash))) recordFailure(keys)
    limiter.succeed(keys[0])
  }

  /**
   * Accepts a TOTP code for the user's active secret, advancing the replay guard. Throws
   * rate_limited while the account's code budget is exhausted; a wrong code spends from it.
   */
  const acceptCode = (row: UserRow, code: string): boolean => {
    const key = totpKey(row.id)
    guardRate([key])
    let ok = false
    if (row.totp_enabled && row.totp_secret) {
      const secret = base32Decode(box.open(row.totp_secret))
      const step = verifyTotp(secret, code, now(), { lastStep: row.totp_last_step })
      ok = step !== null && users.advanceTotpStep(row.id, step)
    }
    if (ok) limiter.succeed(key)
    else limiter.fail(key)
    return ok
  }

  const pruneChallenges = () => {
    const t = now()
    for (const [id, c] of challenges) if (c.expiresAt <= t) challenges.delete(id)
    while (challenges.size >= MAX_PENDING_CHALLENGES) {
      const oldest = challenges.keys().next().value
      if (oldest === undefined) break
      challenges.delete(oldest)
    }
  }

  return {
    state(): SessionState {
      return { userId: session?.userId ?? null, locked: session?.locked ?? false }
    },

    async signup(input: {
      username: string
      password: string
      displayName: string
      storageMode: StorageMode
      language: Language
    }): Promise<PublicUser> {
      if (input.storageMode === 'cloud') fail('cloud_unavailable')
      if (users.findByUsername(input.username)) fail('username_taken')
      const passwordHash = await hashPassword(input.password)
      const id = randomUUID()
      const settings: UserSettings = { ...DEFAULT_SETTINGS, language: input.language }
      try {
        users.insert({
          id,
          username: input.username,
          displayName: input.displayName || input.username,
          passwordHash,
          storageMode: 'local',
          settings,
          now: now()
        })
      } catch (err) {
        if (isUniqueViolation(err)) fail('username_taken')
        throw err
      }
      return startSession(users.findById(id)!)
    },

    async login(input: { username: string; password: string }): Promise<LoginResult> {
      const keys = [userKey(input.username), GLOBAL_KEY]
      guardRate(keys)
      const row = users.findByUsername(input.username)
      if (!row) {
        // Equalise timing so response latency does not reveal which usernames exist.
        await verifyPassword(input.password, decoyHash)
        return recordFailure(keys)
      }
      if (!(await verifyPassword(input.password, row.password_hash))) return recordFailure(keys)
      keys.forEach((k) => limiter.succeed(k))
      if (needsRehash(row.password_hash)) users.updatePassword(row.id, await hashPassword(input.password), now())

      if (row.totp_enabled) {
        pruneChallenges()
        const challenge = randomBytes(32).toString('base64url')
        challenges.set(challenge, { userId: row.id, expiresAt: now() + CHALLENGE_TTL_MS, attempts: 0 })
        return { status: 'totp_required', challenge }
      }
      return { status: 'ok', user: startSession(row) }
    },

    verifyTotp(input: { challenge: string; code: string }): PublicUser {
      const c = challenges.get(input.challenge)
      if (!c || c.expiresAt <= now()) {
        challenges.delete(input.challenge)
        return fail('challenge_expired')
      }
      const row = users.findById(c.userId)
      if (!row) {
        challenges.delete(input.challenge)
        return fail('challenge_expired')
      }
      if (!acceptCode(row, input.code)) {
        c.attempts++
        if (c.attempts >= CHALLENGE_MAX_ATTEMPTS) {
          challenges.delete(input.challenge)
          return fail('challenge_expired')
        }
        return fail('invalid_totp')
      }
      challenges.delete(input.challenge)
      return startSession(users.findById(row.id)!)
    },

    logout(): null {
      session = null
      return null
    },

    me(): { user: PublicUser | null; locked: boolean } {
      if (!session) return { user: null, locked: false }
      const row = users.findById(session.userId)
      if (!row) {
        session = null
        return { user: null, locked: false }
      }
      return { user: toPublicUser(row), locked: session.locked }
    },

    lock(): null {
      currentRow()
      session!.locked = true
      session!.pendingTotp = null
      return null
    },

    async unlock(input: { password: string }): Promise<null> {
      const row = currentRow()
      if (!session!.locked) return null
      await confirmPassword(row, input.password)
      if (session?.userId === row.id) session.locked = false
      return null
    },

    async changePassword(input: { current: string; next: string }): Promise<null> {
      const row = currentRow()
      await confirmPassword(row, input.current)
      users.updatePassword(row.id, await hashPassword(input.next), now())
      return null
    },

    updateProfile(input: { displayName: string }): PublicUser {
      const row = currentRow()
      users.updateDisplayName(row.id, input.displayName || row.username, now())
      return toPublicUser(users.findById(row.id)!)
    },

    updateSettings(patch: Partial<UserSettings>): PublicUser {
      const row = currentRow()
      const next: Record<string, unknown> = { ...toPublicUser(row).settings }
      for (const [key, value] of Object.entries(patch)) if (value !== undefined) next[key] = value
      users.updateSettings(row.id, next as unknown as UserSettings, now())
      return toPublicUser(users.findById(row.id)!)
    },

    async totpBegin(): Promise<TotpSetup> {
      const row = currentRow()
      const secret = generateTotpSecret()
      session!.pendingTotp = secret
      const b32 = base32Encode(secret)
      const url = otpauthUrl(row.username, b32)
      const qrDataUrl = await QRCode.toDataURL(url, { errorCorrectionLevel: 'M', margin: 1, width: 240 })
      return { secret: b32, otpauthUrl: url, qrDataUrl }
    },

    totpEnable(input: { code: string }): PublicUser {
      const row = currentRow()
      const pending = session!.pendingTotp
      if (!pending) return fail('totp_not_started')
      const step = verifyTotp(pending, input.code, now(), { lastStep: row.totp_last_step })
      if (step === null) return fail('invalid_totp')
      users.setTotp(row.id, box.seal(base32Encode(pending)), true, step, now())
      session!.pendingTotp = null
      return toPublicUser(users.findById(row.id)!)
    },

    async totpDisable(input: { password: string; code: string }): Promise<PublicUser> {
      const row = currentRow()
      if (!row.totp_enabled) return toPublicUser(row)
      await confirmPassword(row, input.password)
      if (!acceptCode(row, input.code)) return fail('invalid_totp')
      const fresh = users.findById(row.id)!
      users.setTotp(row.id, null, false, fresh.totp_last_step, now())
      return toPublicUser(users.findById(row.id)!)
    },

    async deleteAccount(input: { password: string }): Promise<null> {
      const row = currentRow()
      await confirmPassword(row, input.password)
      users.remove(row.id)
      session = null
      return null
    }
  }
}

export type AuthService = ReturnType<typeof createAuthService>
